<#
.SYNOPSIS
    Publishes a reviewable snapshot of the P0 verification evidence.

.DESCRIPTION
    `scripts/verify-p0.ps1` writes raw evidence to `.p0-evidence/`, which is
    git-ignored because it contains Pi session transcripts (full prompts and
    model output). This script copies only the reviewable subset — console
    output, exit codes, run status, logs — into
    `docs/verification/evidence/<yyyy-MM-dd>/` so a reviewer can audit what was
    actually executed without pulling raw agent transcripts into the repository.

    Raw Pi session files are deliberately NOT copied.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\scripts\export-evidence.ps1
#>
[CmdletBinding()]
param(
    [string]$EvidenceDir = '',
    [string]$TargetRoot = ''
)

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($EvidenceDir)) { $EvidenceDir = Join-Path $RepoRoot '.p0-evidence' }
if ([string]::IsNullOrWhiteSpace($TargetRoot)) { $TargetRoot = Join-Path $RepoRoot ('docs\verification\evidence\' + (Get-Date -Format 'yyyy-MM-dd')) }

if (-not (Test-Path $EvidenceDir)) { throw "No evidence at $EvidenceDir. Run scripts\verify-p0.ps1 first." }
New-Item -ItemType Directory -Force -Path $TargetRoot | Out-Null

# Files that are safe and useful to review. Anything else (notably
# `pi-sessions/`) stays local.
$include = @(
    'summary.json',
    'full-run-console.txt',
    'p0-01\environment.txt',
    'p0-01\pi-empty-dir-smoke.txt',
    'p0-02\integration-status.txt',
    'p0-02\probe-run.txt',
    'p0-02\capture-probe.txt',
    'p0-03\workflow-info.txt',
    'p0-03\phase1-run.txt',
    'p0-03\phase2-resume.txt',
    'p0-03\phase3-resume.txt',
    'p0-03\final-status.txt',
    'p0-03\reject-path.txt'
)

$copied = @()
foreach ($rel in $include) {
    $src = Join-Path $EvidenceDir $rel
    if (-not (Test-Path $src)) { Write-Warning "missing: $rel"; continue }
    $dst = Join-Path $TargetRoot $rel
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dst) | Out-Null
    Copy-Item -Path $src -Destination $dst -Force
    $copied += $rel
}

# Snapshot the run state that the P0-03 checks asserted on (status + log only;
# the prompt text lives in state.json and is not needed for review).
$runsDir = Join-Path $RepoRoot '.specify\workflows\runs'
if (Test-Path $runsDir) {
    $lines = New-Object System.Collections.ArrayList
    [void]$lines.Add('# Spec Kit run state snapshot')
    [void]$lines.Add('')
    [void]$lines.Add('Generated by `scripts/export-evidence.ps1` from `.specify/workflows/runs/`.')
    foreach ($run in Get-ChildItem $runsDir -Directory) {
        $statePath = Join-Path $run.FullName 'state.json'
        if (-not (Test-Path $statePath)) { continue }
        $state = Get-Content $statePath -Raw -Encoding UTF8 | ConvertFrom-Json
        [void]$lines.Add('')
        [void]$lines.Add("## run ``$($state.run_id)`` — $($state.workflow_id)")
        [void]$lines.Add('')
        [void]$lines.Add("- status: ``$($state.status)``")
        [void]$lines.Add("- current_step: ``$($state.current_step_id)`` (index $($state.current_step_index))")
        [void]$lines.Add("- created_at: $($state.created_at)")
        [void]$lines.Add("- updated_at: $($state.updated_at)")
        if ($state.error) { [void]$lines.Add("- error: ``$($state.error)``") }
        [void]$lines.Add('')
        [void]$lines.Add('| step | status |')
        [void]$lines.Add('| --- | --- |')
        foreach ($prop in $state.step_results.PSObject.Properties) {
            [void]$lines.Add("| $($prop.Name) | $($prop.Value.status) |")
        }
        $logPath = Join-Path $run.FullName 'log.jsonl'
        if (Test-Path $logPath) {
            [void]$lines.Add('')
            [void]$lines.Add('```text')
            Get-Content $logPath -Encoding UTF8 | Where-Object { $_.Trim() } | ForEach-Object {
                $e = $_ | ConvertFrom-Json
                [void]$lines.Add("$($e.timestamp)  $($e.event.PadRight(18)) $($e.step_id) $($e.status)")
            }
            [void]$lines.Add('```')
        }
    }
    $stateOut = Join-Path $TargetRoot 'run-state-snapshot.md'
    [System.IO.File]::WriteAllText($stateOut, ($lines -join "`n"), (New-Object System.Text.UTF8Encoding $false))
    $copied += 'run-state-snapshot.md'
}

$manifest = New-Object System.Collections.ArrayList
[void]$manifest.Add('# Evidence manifest')
[void]$manifest.Add('')
[void]$manifest.Add("Source: ``$EvidenceDir``")
[void]$manifest.Add('')
[void]$manifest.Add('Raw Pi session transcripts are intentionally excluded.')
[void]$manifest.Add('')
[void]$manifest.Add('| file | sha256 | bytes |')
[void]$manifest.Add('| --- | --- | --- |')
foreach ($rel in $copied) {
    $dst = Join-Path $TargetRoot $rel
    $hash = (Get-FileHash $dst -Algorithm SHA256).Hash.ToLowerInvariant()
    [void]$manifest.Add("| ``$($rel -replace '\\','/')`` | ``$hash`` | $((Get-Item $dst).Length) |")
}
[System.IO.File]::WriteAllText((Join-Path $TargetRoot 'MANIFEST.md'), ($manifest -join "`n"), (New-Object System.Text.UTF8Encoding $false))

Write-Host "Evidence snapshot written to: $TargetRoot"
$copied | ForEach-Object { Write-Host "  $_" }
